/* ==================== ДЕМО: ДАННЫЕ ====================
   Только для демо-сборки (demo/build.js), в рабочее приложение не попадает.
   Выдуманная мастерица: прайс, склад, журнал работ и траты — с 1-го числа три месяца назад
   по сегодняшний день. Всё считается от «сегодня», поэтому демо не устаревает: текущий
   месяц всегда заполнен, отчёт всегда показывает четыре месяца.
   Склад не нарисован, а прожит день за днём: работы списывают граммы, закупка приходит,
   когда позиция подходит к минимуму, Lumia в третьем месяце дорожает. Поэтому остатки,
   траты на материалы и себестоимость сходятся так же, как в настоящем учёте.
   Зерно случайности фиксированное: в один и тот же день у всех одни и те же цифры.
   Кладёт результат в DB (нормы услуг читаются оттуда) и его же возвращает. */

