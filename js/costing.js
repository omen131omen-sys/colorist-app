/* ==================== ЦЕХ «ЭКОНОМИКА» ====================
   Как считаются деньги: цена за грамм, светофор маржи, с какой даты маржа честная,
   нормы расхода (уход и мелочь по средней цене) и себестоимость работы.
   Чистая логика без DOM. Подробно: docs/workshops/costing.md */

const gpr = m => m.цена_упаковки / m.нетто_г;              // цена за грамм
// Светофор маржи: <0 — в минус, <45% — низкая, иначе норма.
const AMBER_MARGIN = 45;
function margLevel(marg, price){
  if(marg < 0) return {c:'var(--red)', b:'r', t:'в минус'};
  const p = price ? marg/price*100 : 0;
  if(p < AMBER_MARGIN) return {c:'var(--amber)', b:'a', t:'низкая маржа'};
  return {c:'var(--green)', b:'g', t:''};
}

/* Маржу считаем только с 1 сентября. Августовские работы заносились задним числом без формул,
   поэтому себестоимость у них 0 и маржа выходила 100% — такие цифры портили всю аналитику.
   Выручка и количество работ за август считаются как обычно, исключена только маржа. */
