function нById(id){ return (DB.нормы||[]).find(n=>n.id===id); }
function нормаСумма(n){ return (n.кол||0)*(n.цена||0)*(1+(n.накидка||0)/100); }
/* Строки типового расхода услуги: свои плюс общие («Мелочь» идёт во все работы). */
function нормыУслуги(s){
  const out=((s&&s.нормы)||[]).filter(x=>нById(x.id)).map(x=>({id:x.id, кол:x.кол||0}));
  if(!s || !s.без_общих) (DB.нормы||[]).filter(n=>n.всем).forEach(n=>{
    if(!out.find(o=>o.id===n.id)) out.push({id:n.id, кол:1});
  });
  return out;
}
/* Снимок в работу: цены со временем меняются, а старая работа должна остаться как была. */
function снимокНорм(list){
  return (list||[]).map(x=>{
    const n=нById(x.id); if(!n) return null;
    return {норма_id:n.id, название:n.название, ед:n.ед, кол:x.кол||0,
            цена:n.цена||0, накидка:n.накидка||0};
  }).filter(x=>x && x.кол>0);
}

/* Сколько реально ушло со склада по шагу работы. У старых записей поля нет —
   там списание в ноль не упиралось, берём запрошенное. */
function спис(s){ return s.списано!=null ? s.списано : (s.факт_граммы||0); }
function списШт(p){ return p.списано!=null ? p.списано : (p.кол_во||0); }

/* стоимость работы по её шагам (без списания склада) */
function calcCost(w, materials){
  const mp = Object.fromEntries(materials.map(m=>[m.id,m]));
  let c = 0;
  (w.шаги||[]).forEach(s=>{
    const m = mp[s.материал_id]; const ox = mp[s.оксид_id];
    if(m) c += (s.факт_граммы||0)*gpr(m);
    if(ox) c += (s.факт_оксида||0)*gpr(ox);
  });
  (w.штучные||[]).forEach(p=> c += (p.кол_во||0)*(p.цена_за_штуку||0));
  (w.нормы||[]).forEach(n=> c += нормаСумма(n));
  return Math.round(c);
}
