/* ==================== ЦЕХ «ХРАНИЛИЩЕ» ====================
   База DB в localStorage: пустой старт, загрузка, сохранение (+ запуск синхронизации),
   миграции старых форматов и поиск записей по id. Подробно: docs/workshops/store.md */

/* ==================== СИД ==================== */
function seed(){
  // Пустой старт: демо-данных нет. Реальные остатки приходят через
  // «Восстановить из копии» или синхронизацию с сервером.
  return {materials:[], pieces:[], services:[], works:[], purchases:[], expenses:[],
          equipment:[], нормы:нормыПоУмолчанию(), поставщики:[], _v:4};
}

/* ==================== ХРАНИЛИЩЕ ==================== */
const APP_BUILD = '2026-11-24 · 28';   // поднимать при каждой выкладке
const KEY = 'colorist_v7';
let DB;
function load(){
  try{ DB = JSON.parse(localStorage.getItem(KEY)); }catch(e){ DB=null; }
  if(!DB || !DB.materials){ DB = seed(); save(); }
  мигрируй();
}
/* Дочистка базы до текущего формата. Вызывается не только при старте: данные приезжают
   ещё и с сервера, и из файла копии — там они в том виде, в каком их сохранило старое
   приложение, и без этой обработки поедут цены и типовой расход. */
function мигрируй(){
  if(!DB.purchases) DB.purchases=[];
  // Единый журнал расходов + список оборудования
  if(!DB.expenses){
    DB.expenses = (DB.purchases||[]).map(b=>({id:b.id||uid('e'), дата:b.дата, категория:'материалы',
      сумма:b.сумма||0, заметка:(b.название||'Закупка')+(b.кол?' · '+b.кол:''), материал_id:b.материал_id||null}));
  }
  if(!DB.equipment) DB.equipment=[];
  if(!DB.нормы) DB.нормы=нормыПоУмолчанию();
  if(!Array.isArray(DB.поставщики)) DB.поставщики=[];   // заказ поставщику (цех «Заказ»), с 24.11
  // Типовой расход раскладываем по услугам один раз: дальше это её данные, не наши.
  if(!DB._нормы1){
    (DB.services||[]).forEach(s=>{
      if(s.нормы) return;
      const hit=ТИПОВОЙ_РАСХОД.find(([re])=>re.test(s.название||''));
      s.нормы = hit ? Object.keys(hit[1]).map(id=>({id, кол:hit[1][id]})) : [];
      if(hit && hit[2]) s.без_общих=true;
    });
    DB._нормы1=1;
  }
  // Сентябрьские работы заносились до того, как появился типовой расход — проставляем его
  // задним числом и пересчитываем маржу. Август не трогаем: там и материалы не заносились.
  if(!DB._нормыРаботы1){
    (DB.works||[]).forEach(w=>{
      if(!margCounted(w) || (w.нормы||[]).length) return;
      const s=sById(w.услуга_id); if(!s) return;
      w.нормы=снимокНорм(нормыУслуги(s));
      w.себестоимость=calcCost(w, DB.materials);
      w.маржа=w.цена-w.себестоимость;
    });
    DB._нормыРаботы1=1;
  }
  // Оксиды у разных брендов зовутся одинаково («Оксид 6%»), в выпадашке было не различить —
  // дописываем бренд в название. Идемпотентно: второй раз не добавится.
  (DB.materials||[]).forEach(m=>{
    if(m.тип!=='оксид') return;
    const br=(m.бренд||'').trim(); if(!br || br==='—') return;
    const key=br.toLowerCase().split(/\s+/)[0];
    if(!m.название.toLowerCase().includes(key)) m.название = m.название.trim()+' · '+br;
  });
  // «Еда» была отдельной категорией не с самого начала — переносим то, что писали в «прочее».
  (DB.expenses||[]).forEach(e=>{
    if(e.категория==='прочее' && /^\s*(еда|обед|перекус|продукт\w*)\s*$/i.test(e.заметка||'')) e.категория='еда';
  });
  // Услуги стали прайс-листом: одна «цена» → вилка «от–до», типовой рецепт больше не хранится.
  (DB.services||[]).forEach(s=>{
    if(s.цена_от==null){ s.цена_от=s.цена||0; s.цена_до=0; }
    delete s.цена; delete s.формула;
  });
}
function save(){ DB._updatedAt=Date.now(); localStorage.setItem(KEY, JSON.stringify(DB)); scheduleSync(); }
function mById(id){ return DB.materials.find(m=>m.id===id); }
function pById(id){ return DB.pieces.find(p=>p.id===id); }
function sById(id){ return DB.services.find(s=>s.id===id); }
