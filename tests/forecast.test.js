/* «На сколько хватит»: прогноз остатка по темпу расхода за последние 60 дней. */
const { test } = require('node:test');
const assert = require('node:assert/strict');
const { loadApp, MATERIALS, emptyDB } = require('./helpers');

const app = loadApp(emptyDB({ materials: MATERIALS }));
const раб = (дата, шаги) => ({ дата, шаги });
const дн = (m, works, сегодня = '2026-11-24') =>
  app.run('хватитДней(__arg.m, __arg.works, __arg.сегодня)', { m, works, сегодня });

test('темп по окну 60 дней: 120 г за 60 дней, остаток 100 г → 50 дней', () => {
  const works = [
    раб('2026-09-26', [{ материал_id: 'l62', факт_граммы: 60 }]),   // ровно 59 дней назад — в окне
    раб('2026-11-20', [{ материал_id: 'l62', факт_граммы: 60 }]),
    раб('2026-09-01', [{ материал_id: 'l62', факт_граммы: 500 }]),  // за окном — не считается
  ];
  assert.equal(дн({ id: 'l62', остаток_г: 100 }, works), 50);
});

test('оксид считается и как отдельная строка, и как оксид шага', () => {
  const works = [
    раб('2026-10-01', [{ материал_id: 'ox15', факт_граммы: 90 }]),
    раб('2026-11-01', [{ материал_id: 'l62', факт_граммы: 30, оксид_id: 'ox15', факт_оксида: 30 }]),
  ];
  // 120 г, первое использование 54 дня назад → окно 55 дней; 1000 г / (120/55) ≈ 458
  assert.equal(дн({ id: 'ox15', остаток_г: 1000 }, works), 458);
});

test('новый материал: окно не меньше двух недель', () => {
  const works = [
    раб('2026-11-22', [{ материал_id: 'l923', факт_граммы: 10 }]),
    раб('2026-11-24', [{ материал_id: 'l923', факт_граммы: 18 }]),
  ];
  // 28 г за 3 дня дали бы «на 10 дней»; с окном 14 дней — 28/14 = 2 г в день → 50 дней
  assert.equal(дн({ id: 'l923', остаток_г: 100 }, works), 50);
});

test('одно использование — прогноза нет; пустой остаток — 0; будущие даты не считаются', () => {
  assert.equal(дн({ id: 'pwd', остаток_г: 300 }, [раб('2026-11-10', [{ материал_id: 'pwd', факт_граммы: 40 }])]), null);
  assert.equal(дн({ id: 'pwd', остаток_г: 0 }, []), 0);
  const будущее = [
    раб('2026-11-10', [{ материал_id: 'pwd', факт_граммы: 40 }]),
    раб('2026-12-01', [{ материал_id: 'pwd', факт_граммы: 40 }]),
  ];
  assert.equal(дн({ id: 'pwd', остаток_г: 300 }, будущее), null);
});

test('подпись: дни → недели → месяцы → «больше года»', () => {
  const п = d => app.run('подписьХватит(__arg)', d);
  assert.equal(п(null), '');
  assert.equal(п(0), 'закончился');
  assert.equal(п(1), '≈ 1 день');
  assert.equal(п(3), '≈ 3 дня');
  assert.equal(п(12), '≈ 12 дней');
  assert.equal(п(21), '≈ 3 недели');
  assert.equal(п(50), '≈ 7 недель');
  assert.equal(п(70), '≈ 2 месяца');
  assert.equal(п(160), '≈ 5 месяцев');
  assert.equal(п(400), 'больше года');
});
