/* Формула голосом: что бы ни написала диктовка, на выходе — формула, которую понимает разбор. */
const { test } = require('node:test');
const assert = require('node:assert/strict');
const { loadApp, MATERIALS, emptyDB } = require('./helpers');

const app = loadApp(emptyDB({ materials: MATERIALS }));
const г = text => app.run('голосВФормулу(__arg)', text);
// итог целиком: голос → разбор → [материал, граммы]
const разбор = text => app.run('parseFormulaText(голосВФормулу(__arg), DB.materials).map(l=>[l.материал_id, l.граммы])', text);

test('цифрами, как пишет клавиатура iPhone', () => {
  assert.equal(г('6,2 30 грамм плюс 6,1 15 грамм плюс 1,5% 90 грамм'), '6.2 30гр + 6.1 15гр + 1.5% 90гр');
  assert.equal(г('9.23 20 г + 10.12 5 г.'), '9.23 20гр + 10.12 5гр');
  assert.equal(г('Люмия 6.21 30 гр'), 'люмия 6.21 30гр');
});

test('словами: «шесть два тридцать грамм»', () => {
  assert.equal(г('шесть два тридцать грамм плюс полтора процента девяносто граммов'), '6.2 30гр + 1.5% 90гр');
  assert.equal(г('девять двадцать три двадцать грамм'), '9.23 20гр');          // двадцать три — одно число
  assert.equal(г('десять двенадцать пятнадцать грамм'), '10.12 15гр');
  assert.equal(г('шесть ноль сорок пять грамм'), '6.0 45гр');
  assert.equal(г('шесть точка двадцать один тридцать грамм'), '6.21 30гр');
  assert.equal(г('оксид шесть процентов сто двадцать грамм'), 'оксид 6% 120гр');
});

test('слитно: «62 30 г» — это 6.2; без «плюс» строки делятся по граммам', () => {
  assert.equal(г('62 30 г'), '6.2 30гр');
  assert.equal(г('1012 15 грамм'), '10.12 15гр');
  assert.equal(г('6.2 30 грамм 3.0 15 грамм 1,5 процента 45 грамм'), '6.2 30гр + 3.0 15гр + 1.5% 45гр');
});

test('пудра и оксид без слова «процент»; граммы без единицы', () => {
  assert.equal(г('пудра 30 грамм плюс оксид 6 90 грамм'), 'пудра 30гр + оксид 6% 90гр');
  assert.equal(г('6% 90'), '6% 90гр');
  assert.equal(г('7.1 35'), '7.1 35гр');
});

test('«би би» — серия BB', () => {
  assert.equal(г('би би 6.2 20 грамм'), 'bb 6.2 20гр');
});

test('до конца: голос находит материалы склада и граммы', () => {
  assert.deepEqual(разбор('люмия шесть два тридцать грамм плюс полтора процента девяносто грамм'),
    [['l62', 30], ['ox15', 90]]);
  assert.deepEqual(разбор('10,12 15 г плюс 9.23 5 г'), [['l1012', 15], ['l923', 5]]);
  assert.deepEqual(разбор('пудра тридцать грамм плюс оксид 6% Лонда девяносто грамм'), [['pwd', 30], ['ox6l', 90]]);
});
